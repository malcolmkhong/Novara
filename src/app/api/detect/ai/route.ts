const bodySchema = z.object({
  text: z.string().min(1).max(20000),
  textType: z.enum(["general", "novel"]).default("general"),
});

const AI_SYSTEM_PROMPT = `You are an expert AI-content forensic analyst. Determine the probability that the given text was generated by an AI language model rather than written by a human. Evaluate: uniform sentence rhythm (low burstiness), generic or templated phrasing, listy/evenly-balanced structure, over-hedging, absence of personal voice or idiosyncrasy, perfect grammar, hallmark AI transition words. Respond with ONLY valid JSON — no markdown fences, no commentary — in exactly this shape: {"score": <integer 0-100 = probability the text is AI-generated>, "confidence": <integer 0-100 = your confidence>, "verdict": "ai"|"human"|"mixed"|"uncertain", "summary": "<2-3 sentence explanation>", "signals": [{"label": "...", "description": "...", "severity": "high"|"medium"|"low"|"info"}], "sentences": [{"text": "<exact sentence copied from the input>", "aiLikelihood": <integer 0-100>, "note": "<short reason>"}]}. List every sentence of the provided text, up to a maximum of 30 sentences; keep each note under 12 words. Be concise.`;

const NOVEL_SYSTEM_PROMPT = `You are a fiction-forensics expert who detects AI-generated NOVEL PROSE. Judge the text as creative fiction — narrative, scene, or dialogue — not as an essay. Look for hallmark LLM fiction tells: purple or overwrought metaphors and over-description; emotional over-narration (telling feelings instead of showing them); formulaic dialogue tags with adverbs ("she said softly", "he murmured gently"); heavy em-dash use and trailing participial phrases (", turning toward her"); tricolon sentence rhythm (three parallel clauses); evenly-cadenced paragraphs; generic sensory filler ("the air hung heavy", "a mixture of awe and fear"); stock phrases ("couldn't help but", "let out a breath she didn't know she was holding", "something shifted", "eyes widened", "a beat of silence", "heart pounded against her ribs"); absence of a distinctive narrative voice, idiolect, or productive messiness; overly safe, polished, conflict-free storytelling. Also weigh what makes prose feel HUMAN: irregular rhythm, specific odd details, subtext, imperfect grammar used deliberately, distinct character voices, restraint. Respond with ONLY valid JSON — no markdown fences, no commentary — in exactly this shape: {"score": <integer 0-100 = probability the prose is AI-generated>, "confidence": <integer 0-100 = your confidence>, "verdict": "ai"|"human"|"mixed"|"uncertain", "summary": "<2-3 sentence explanation focused on craft>", "signals": [{"label": "...", "description": "...", "severity": "high"|"medium"|"low"|"info"}], "sentences": [{"text": "<exact sentence or dialogue line copied from the input>", "aiLikelihood": <integer 0-100>, "note": "<short reason>"}]}. List up to 30 sentences or dialogue lines of the provided text; keep each note under 12 words. Be concise.`;

// ---------------------------------------------------------------------------
// Types (AI output is untrusted — validated defensively below)
// ---------------------------------------------------------------------------

type Severity = "high" | "medium" | "low" | "info";
type Verdict = "ai" | "human" | "mixed" | "uncertain";

const SEVERITIES: readonly Severity[] = ["high", "medium", "low", "info"];
const VERDICTS: readonly Verdict[] = ["ai", "human", "mixed", "uncertain"];

interface DetectedSignal {
  label: string;
  description: string;
  severity: Severity;
}

interface DetectedSentence {
  text: string;
  aiLikelihood: number;
  note?: string;
}

interface AiAnalysis {
  score: number; // required — without it the parse is considered failed
  confidence: number;
  verdict: Verdict | null; // null -> derived from composite score
  summary: string;
  signals: DetectedSignal[];
  sentences: DetectedSentence[];
}

// ---------------------------------------------------------------------------
// AI plumbing (server-side only)
// ---------------------------------------------------------------------------

interface AiMessage {
  role: "assistant" | "user";
  content: string;
}

function buildMessages(
  text: string,
  textType: "general" | "novel",
  forceJson: boolean,
): AiMessage[] {
  const userContent = forceJson
    ? `Analyze this text:\n\n${text}\n\nReturn only the JSON object.`
    : `Analyze this text:\n\n${text}`;
  return [
    {
      role: "assistant",
      content: textType === "novel" ? NOVEL_SYSTEM_PROMPT : AI_SYSTEM_PROMPT,
    },
    { role: "user", content: userContent },
  ];
}

/** Pull the plain-text reply out of an untyped SDK completion payload. */
function extractCompletionContent(completion: unknown): string | null {
  if (typeof completion !== "object" || completion === null) return null;
  const choices = (completion as { choices?: unknown }).choices;
  if (!Array.isArray(choices) || choices.length === 0) return null;
  const first = choices[0];
  if (typeof first !== "object" || first === null) return null;
  const message = (first as { message?: unknown }).message;
  if (typeof message !== "object" || message === null) return null;
  const content = (message as { content?: unknown }).content;
  return typeof content === "string" ? content : null;
}

/**
 * What the calls of this request actually cost (Step 55/56 — the spend gate).
 * Every provider call that MEASURED tokens is charged; a failed call
 * measures nothing and costs nothing.
 */
export interface MeasuredSpend {
  credits: number;
  calls: number;
  note: string | null;
}

/**
 * One AI request. Returns the reply text, or null on ANY failure
 * (transport error, empty content, unexpected shape). Never throws.
 */
async function requestText(
  messages: AiMessage[],
  measured: MeasuredSpend,
): Promise<string | null> {
  // Policy F (P5-b): ZAI.create() failing below is a PRE-SEND failure — no
  // row (F3). A sent attempt that produces no completion payload records one
  // zero-token failed row (F1); a completion without usage records nothing (F4).
  let sent = false;
  try {
    const zai = await ZAI.create();
    sent = true;
    const completion: unknown = await zai.chat.completions.create({
      messages,
      thinking: { type: "disabled" },
    });
    // Persist the per-call row (standalone detector — global-only, never
    // culminates in a novel).
    const usage = extractRealUsage(completion);
    recordUsageCall({ surface: "detect", usage });
    if (usage) {
      // The measured cost of THIS call. The request carried no model field,
      // so the price comes from the default model's row (priced-by-fallback).
      const charged = creditsFromUsage(
        GATEWAY_DEFAULT_MODEL_ID,
        usage.promptTokens,
        usage.completionTokens,
      );
      measured.credits += charged.credits;
      measured.calls += 1;
      measured.note = charged.note ?? measured.note;
    }
    return extractCompletionContent(completion);
  } catch (error) {
    if (sent) {
      recordUsageCall({
        surface: "detect",
        usage: null,
        status: "failed",
        errorKind: classifyAiFailure(error),
      });
    }
    console.error("[detect/ai] AI request failed:", error);
    return null;
  }
}

// ---------------------------------------------------------------------------
// Defensive parsing of AI JSON
// ---------------------------------------------------------------------------

function mapSignal(value: unknown): DetectedSignal | null {
  if (typeof value !== "object" || value === null) return null;
  const record = value as Record<string, unknown>;
  const label = typeof record.label === "string" ? record.label.trim() : "";
  if (!label) return null;
  const description =
    typeof record.description === "string" ? record.description.trim() : "";
  const severity: Severity =
    typeof record.severity === "string" &&
    (SEVERITIES as readonly string[]).includes(record.severity)
      ? (record.severity as Severity)
      : "info";
  return { label, description, severity };
}

function mapSentence(value: unknown): DetectedSentence | null {
  if (typeof value !== "object" || value === null) return null;
  const record = value as Record<string, unknown>;
  const text = typeof record.text === "string" ? record.text.trim() : "";
  if (!text) return null;
  const aiLikelihood =
    typeof record.aiLikelihood === "number" &&
    Number.isFinite(record.aiLikelihood)
      ? clamp(Math.round(record.aiLikelihood), 0, 100)
      : 50;
  const note =
    typeof record.note === "string" && record.note.trim().length > 0
      ? record.note.trim()
      : undefined;
  return note !== undefined
    ? { text, aiLikelihood, note }
    : { text, aiLikelihood };
}

function parseAnalysis(raw: string): AiAnalysis | null {
  const parsed: unknown = extractJson(raw);
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    return null;
  }
  const record = parsed as Record<string, unknown>;

  // `score` is the one field we cannot synthesize — missing/invalid = failed parse.
  if (typeof record.score !== "number" || !Number.isFinite(record.score)) {
    return null;
  }
  const score = clamp(Math.round(record.score), 0, 100);

  const confidence =
    typeof record.confidence === "number" && Number.isFinite(record.confidence)
      ? clamp(Math.round(record.confidence), 0, 100)
      : 0;

  const verdict: Verdict | null =
    typeof record.verdict === "string" &&
    (VERDICTS as readonly string[]).includes(record.verdict)
      ? (record.verdict as Verdict)
      : null;

  const summary = typeof record.summary === "string" ? record.summary : "";

  const signals = Array.isArray(record.signals)
    ? record.signals
        .map(mapSignal)
        .filter((signal): signal is DetectedSignal => signal !== null)
    : [];

  const sentences = Array.isArray(record.sentences)
    ? record.sentences
        .map(mapSentence)
        .filter((sentence): sentence is DetectedSentence => sentence !== null)
    : [];

  return { score, confidence, verdict, summary, signals, sentences };
}

function deriveVerdict(aiScore: number): Verdict {
  if (aiScore >= 65) return "ai";
  if (aiScore >= 40) return "mixed";
  return "human";
}

/** Composite: 70% AI judgment + 30% local heuristics, clamped to 0-100. */
function compositeScore(llmScore: number, heuristics: HeuristicResult): number {
  return clamp(
    Math.round(0.7 * llmScore + 0.3 * heuristics.heuristicScore),
    0,
    100,
  );
}

